"""Phase 6A experiment inventory, generated from the committed aggregates (results/experiments/*.json), the
regeneration records (results/regeneration/) and the Phase 6B runs that Phase 6A uses. Aggregates only.
Output: PHASE6A_EXPERIMENT_INVENTORY.md
    python -m research_experiments.phase_6a_normal_mild_lstm.inventory
"""
from __future__ import annotations

import json
import re
from collections import defaultdict

from research_experiments.phase_6a_normal_mild_lstm.p6acommon import CONF, EXP, P6A, REGEN, RES, ROOT, guard

EXP6B = ROOT / "research_experiments" / "phase_6b_threshold_sampling_lstm" / "results" / "experiments"
DESC = {"mlpfusion": "MLP fusion (header || ECGFounder f6)", "ecgflindist": "ECGFounder f6 linear, distance-penalised CE",
        "hdrclinlr": "header + clinical LR", "vote": "vote, C1 recipe", "c3": "vote + nested prior rule, C3 recipe",
        "lstmL0": "LSTM L0 (rhythm, 1x uni)", "lstmL1": "LSTM L1 (aligned, 1x uni)", "lstmL2": "LSTM L2 (aligned, 2x uni)",
        "lstmL3": "LSTM L3 (aligned, 1x bi)", "lstmL4": "LSTM L4 (aligned, 2x bi, dropout 0.3)", "lstmsel": "LSTM-sel (nested selection)",
        "L5": "CNN-LSTM (run in 6B)", "F3": "vote of C1 members + LSTM-sel (run in 6B)", "F4": "F3 + nested prior rule (run in 6B)"}


def main():
    groups = defaultdict(list)
    for f in sorted(EXP.glob("*.json")):
        exp, run = f.stem.split("__")
        groups[exp].append((run, json.loads(f.read_text())))
    for pat in ("P6B-L5-ORIG-v1", "P6B-F3-ORIG-v1", "P6B-F4-ORIG-v1"):
        for f in sorted(EXP6B.glob(f"{pat}__*.json")):
            groups[pat].append((f.stem.split("__")[1], json.loads(f.read_text())))
    regen = {f.stem for f in REGEN.glob("*.json")} if REGEN.exists() else set()
    rows = []
    for exp, runs in sorted(groups.items()):
        m = re.match(r"P6[AB]-(\w+)-(\w+)-v\d", exp)
        model, cfg = m.group(1), m.group(2)
        seeds = sorted({int(r.split("_")[0][1:]) for r, _ in runs}); reps = sorted({int(r.split("_r")[1]) for r, _ in runs})
        acc = sum(a["metrics"]["accuracy"] for _, a in runs) / len(runs)
        t = [a.get("train_minutes") for _, a in runs if a.get("train_minutes") is not None]
        nreg = sum(f"{exp}__{r}" in regen for r, _ in runs)
        rows.append(f"| `{exp}` | {DESC.get(model, model)} | {cfg} | {','.join(map(str, seeds))} | {','.join(map(str, reps))} | {len(runs)} | "
                    f"{acc:.3f} | {runs[0][1].get('n_params', '') or ''} | {(sum(t) / len(t)) if t else '':{'.1f' if t else ''}} | "
                    f"{nreg if nreg else ''} |")
    sel = json.loads((RES / "lstm_selection.json").read_text()) if (RES / "lstm_selection.json").exists() else None
    fx = json.loads((CONF / "lstm_fixed.json").read_text())["lstm_fixed"] if (CONF / "lstm_fixed.json").exists() else None
    lines = ["# Phase 6A experiment inventory", "",
             "Generated by `inventory.py` from the committed aggregates. Development set only (837 ECGs); every run is a full",
             "5-fold outer CV of one (seed, repeat) and is scored on all 837 ECGs. Accuracy = original labels, mean over the listed runs",
             "(per-run, not seed-combined; the seed-combined figures are in `PHASE6A_MODEL_COMPARISON.csv`). \"Regenerated\" = private",
             "per-ECG file re-created on the owner's laptop and checked against the committed aggregate (`results/regeneration/`).", "",
             "| Experiment id | Model | Config | Seeds | Repeats | Runs | Mean accuracy | Parameters | Train min / run | Regenerated |",
             "|---|---|---|---|---|---|---|---|---|---|"] + rows + ["",
             "## Configurations", "B1 original labels; B2 consistently linked Mild ECGs with EF >= 50 -> Normal (27); B3 45 uncertain Normal/Mild",
             "ECGs removed from inner-train only; A270 inner-train Normal raised to 270 from inner-val (PHASE6A_PLAN.md sections 3-4).", "",
             "## LSTM selection",
             (f"Nested selection counts over the 15 B1 folds: {sel['counts']}; LSTM-fixed = **{fx}** (rule: {sel['rule']})." if sel else "not run yet"), "",
             "## Analyses without model training",
             "`labels.py` (label rule, cohort facts, configurations), `data_check.py` (owner-supplied matching sheets; C6A-1 date swap),",
             "`feasibility.py` (80 % feasibility), `signals.py` (LSTM inputs), `compare.py` (comparison, statistics, plots).", ""]
    guard(P6A / "PHASE6A_EXPERIMENT_INVENTORY.md").write_text("\n".join(lines))
    print("\n".join(lines[:12 + len(rows)]))


if __name__ == "__main__":
    main()
