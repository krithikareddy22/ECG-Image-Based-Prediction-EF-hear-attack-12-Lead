"""Generate research_experiments/EXPERIMENT_INVENTORY.md: every completed run (phases 1-4) with its configuration,
outputs, key development-CV / fixed-split metrics, status and whether it needs re-running; plus a checkpoint /
artefact inventory (path, size, SHA-256, config, seed, data version, committed or regenerate).
Read-only on all results.   python -m research_experiments.make_inventory
"""
import hashlib
import json
from pathlib import Path

R = Path(__file__).resolve().parent
ROOT = R.parent
COMMIT_ARTEFACTS = {  # artefacts proposed for git (small, reusable); everything else is documented + regenerated
    "research_experiments/phase_2/models/ecgf_aligned_features.npz",
}


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def p2_row(d):
    info = json.loads((d / "info.json").read_text()) if (d / "info.json").exists() else {}
    m = json.loads((d / "cv_metrics.json").read_text())["pooled"] if (d / "cv_metrics.json").exists() else None
    cfg = info.get("cfg") or info.get("method") or info.get("recipe") or ""
    spec = info.get("spec", {}).get("blocks") if isinstance(info.get("spec"), dict) else info.get("members")
    return dict(tag=d.name, config=f"{spec} {cfg}"[:110], repeat=info.get("repeat", 0), seed=info.get("seed", ""),
                acc=m["accuracy"] if m else None, bal=m["balanced_accuracy"] if m else None, mf1=m["macro_f1"] if m else None,
                mild=m["per_class"]["Mild"]["f1"] if m else None, status="complete" if m or (d / "oof.csv").exists() else "incomplete")


def main():
    L = ["# Experiment inventory (auto-generated by `python -m research_experiments.make_inventory`)", "",
         "All metrics: development-set patient-grouped CV (phases 2–4) unless stated. The locked 210-ECG test set has",
         "**not** been scored since phase 1. **No completed run needs re-running.** Every run is stored as",
         "`oof.csv`, `info.json` and `cv_metrics.json` under the listed folder, and runs are idempotent: re-invoking",
         "skips them.", "",
         "Phase 4 run scripts: `phase_4.regression`, `phase_4.multitask`, `phase_4.label_quality`, `phase_4.benchmark4`",
         "(pre-registration `phase_4/configs/PREREG_PHASE4.md`).", ""]
    # phase 1
    L += ["## Phase 1 (fixed split: 669 train / 168 val / 210 test; test EXPOSED)", "",
          "| Run | Input | Test acc | Bal | Macro-F1 | Status |", "|---|---|---|---|---|---|"]
    for f in sorted((R / "results").glob("*/metrics.json")):
        m = json.loads(f.read_text())
        if "test" in m and "accuracy" in m["test"]:
            L.append(f"| `{m['tag']}` | {str(m.get('input', ''))[:50]} | {m['test']['accuracy']:.3f} | {m['test']['balanced_accuracy']:.3f} | "
                     f"{m['test']['macro_f1']:.3f} | complete; no rerun |")
    for ph, base in (("Phase 2", R / "phase_2" / "results"), ("Phase 3", R / "phase_3" / "results")):
        L += ["", f"## {ph} (development CV on 837 ECGs; folds `phase_2/configs/folds_D.csv`)", "",
              "| Run (folder) | Inputs / config | CV repeat | Seed | Acc | Bal | Macro-F1 | Mild F1 | Status | Rerun? |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for d in sorted(p for p in base.iterdir() if p.is_dir()):
            r = p2_row(d)
            f = lambda x: f"{x:.3f}" if isinstance(x, float) else "–"
            L.append(f"| `{r['tag']}` | {r['config'].replace('|', '/')} | {r['repeat']} | {r['seed']} | {f(r['acc'])} | {f(r['bal'])} | "
                     f"{f(r['mf1'])} | {f(r['mild'])} | {r['status']} | no |")
    L += ["", "## Phase 4 (development CV on 837 ECGs / 794 patients; locked test not scored)", "",
          "| Step | Output | Status |", "|---|---|---|",
          "| 4A spreadsheet audit (4 authorised sheets = file-copy logs) | `phase_4/reports/PHASE4_DATA_AUDIT.md` | complete |",
          "| 4A/4B ECG_ECHO matching + label audit | `phase_4/results/audit_matching.json` (aggregates); private link tables (git-ignored) | complete; private tables regenerated by `phase_4.audit_matching` |",
          "| 4B repeat-echo EF variability | `phase_4/results/ef_repeat_variability.json` | complete (uncertainty NOT quantifiable) |",
          "| 4C cohorts A-G + plots | `phase_4/results/cohort_summary.csv`, `phase_4/plots/*.png`; private `cohorts.csv` | complete |",
          "| 4D-4H runs, benchmark, analyses, reports | see the model table below; `phase_4/reports/PHASE4_*.md` | complete |", ""]
    bm = R / "phase_4" / "results" / "phase4_benchmark.csv"
    if bm.exists():
        import pandas as pd
        B = pd.read_csv(bm)
        L += ["### Phase 4 models (seed-combined per repeat, mean over repeats 0-2; aggregates in `phase_4/results/runs/*.json`)", "",
              "Per-ECG predictions are git-ignored (`phase_4/data/private/runs/`); a fresh clone regenerates them deterministically "
              "by re-running the listed script (`phase_4.p4common.done` requires both files).", "",
              "| Model | Family | Runs | Acc | Bal | Macro-F1 | Mild F1 | S3 | ΔS3 vs vote (p) | MAE / R² (G) | Rerun? |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in B.sort_values(["family", "model"]).iterrows():
            reg = f"{r['reg_G:mae']:.2f} / {r['reg_G:r2']:.3f}" if pd.notna(r.get("reg_G:mae")) else "–"
            d = f"{r['vs_vote:all_folder:s3:diff']:+.3f} ({r['vs_vote:all_folder:s3:p']:.2f})" if pd.notna(r.get("vs_vote:all_folder:s3:diff")) else "–"
            L.append(f"| `{r.model}` | {r.family} | {r.runs} | {r['all_folder:accuracy']:.3f} | {r['all_folder:balanced_accuracy']:.3f} | "
                     f"{r['all_folder:macro_f1']:.3f} | {r['all_folder:f1_Mild']:.3f} | {r['all_folder:s3']:.3f} | {d} | {reg} | no |")
        L.append("")
    # artefacts
    L += ["## Checkpoint / artefact inventory", "",
          "| Path | Size MB | SHA-256 (first 16) | What / config / seed / data version | In git? | How to get it back |", "|---|---|---|---|---|---|"]
    desc = {
        "12_lead_ECGFounder.pth": ("ECGFounder 12-lead pre-trained (HF PKUDigitalHealth/ECGFounder rev d9b17939, MIT)", "download (RESUME.md)"),
        "1_lead_ECGFounder.pth": ("ECGFounder 1-lead pre-trained (same revision)", "download (RESUME.md)"),
        "A2_": ("phase-1 partial fine-tune of ECGFounder (stages 5-6 or 6), fixed split train 669 / val 168; seed in name", "`bash research_experiments/run_queue.sh` (~5 min each); predictions already in `results/A2_*`"),
        "B_resnet18": ("phase-1 ResNet-18 ordinal (cum. link), fixed split, seed 42", "`train_deep.py --arch resnet18 --head cumlink` (~37 min)"),
        "repro/R0": ("phase-1 exact retrain of the baseline ResNet-18, seed 42", "`reproduce_resnet18.py` (~25 min)"),
        "img_resnet18_baseline_recipe_fold": ("phase-2 image CNN (original recipe), dev CV repeat 0, fold in name, seed 42", "`phase_2.cv_image_cnn` (~25 min/fold); OOF + locked-test probs already in `phase_2/results/img_resnet18_baseline_recipe/`"),
        "features_ecgfounder_": ("phase-1 frozen ECGFounder features (input variant in name)", "`ecgfounder.extract_features` (~1 min)"),
        "ecgf_aligned_features": ("phase-2 frozen ECGFounder features, 'aligned' input (f4/f5/f6/f6max/logits), all 1,047 ECGs; used by EVERY phase-2/3/4 model", "committed (proposed); else `phase_2.ecgf_features` (~5 min)"),
        "ecgf_": ("phase-2/3 frozen ECGFounder features for an input variant (masking audit)", "`phase_2.ecgf_features` / `phase_3.masking_audit` (~1–5 min)"),
        "cache_stage": ("phase-2 cached ECGFounder activations for partial fine-tuning", "`phase_2.ecgf_features` (~5 min)"),
    }
    for p in sorted(ROOT.glob("research_experiments/**/*")):
        if p.suffix in (".pt", ".pth", ".npz", ".npy", ".joblib") and "results" not in p.parts:
            rel = str(p.relative_to(ROOT))
            d = next((v for k, v in desc.items() if k in p.name or k in rel), ("", "see RESUME.md"))
            L.append(f"| `{rel}` | {p.stat().st_size / 2**20:.1f} | `{sha(p)[:16]}` | {d[0]} | {'yes' if rel in COMMIT_ARTEFACTS else 'no (size / regenerable)'} | {d[1]} |")
    L += ["", "Small CSV features (`phase_3/models/clinical_features.csv`) are listed in HANDOFF.md.", ""]
    (R / "EXPERIMENT_INVENTORY.md").write_text("\n".join(L) + "\n")
    print(f"wrote EXPERIMENT_INVENTORY.md ({len(L)} lines)")


if __name__ == "__main__":
    main()
